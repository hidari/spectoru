//! 現在時刻を解決するポート。
//!
//! `ProjectMeta.extracted_at` は「いつ抽出したか」という副作用そのものであり、
//! これを直接 `SystemTime::now()` から取ると extract の結果が実行時刻に依存して
//! テストが決定的でなくなる。時刻取得をポートに切り出すことで、テストでは固定値を
//! 返す Fake を注入し、IR 全体をスナップショットとして比較できる。
//!
//! 戻り値を `String` にしているのは、`core::ir` に日時型（= 外部 crate）を
//! 持ち込まないため。フォーマットの責務は adapter 側にある。

/// 秒精度の ISO 8601 UTC 文字列（例: `2026-04-13T12:00:00Z`）を返す。
///
/// 実装は必ず `Z` 終端の UTC を返すこと。ローカルタイムゾーンを含む表現は、
/// 生成環境によってフラグメントの内容が変わってしまうため契約違反とする。
pub trait Clock: Send + Sync {
    fn now_iso8601(&self) -> String;
}
